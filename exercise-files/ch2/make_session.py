#!/usr/bin/env python3
"""03_04: build a teaching replica of a Claude Code session transcript (JSONL) using
REAL token counts (requires ANTHROPIC_API_KEY). Real tools (Tokview, claude-devtools)
read Claude Code's actual JSONL in ~/.claude/projects/. This file mimics the shape —
one JSON record per line; assistant records carry usage; tool calls carry the real
token size of what each tool returned into context. Tool results and the billed
input/output are measured with Anthropic's count_tokens (claude-opus-4-8); count_tokens
accepts inputs larger than the context window, so the big app.log read is counted
directly. Run: python3 make_session.py"""
import os, sys, json, subprocess

_MODEL = "claude-opus-4-8"
if not os.environ.get("ANTHROPIC_API_KEY"):
    sys.exit("ERROR: this demo requires a real API key. "
             "Activate the venv and `export ANTHROPIC_API_KEY=sk-...`, then rerun.")
try:
    import anthropic
except ImportError:
    sys.exit("ERROR: `anthropic` not installed. Activate the venv that has it "
             "(e.g. `source ~/.venvs/headroom/bin/activate`).")
_API = anthropic.Anthropic()

def ntok(text):
    """Real input-token count via Anthropic count_tokens. count_tokens accepts inputs
    far larger than the context window, so count directly; fall back to counting a chunk
    and scaling by the character ratio only if the API rejects an oversized request."""
    text = text if text else " "
    try:
        return _API.messages.count_tokens(model=_MODEL,
            messages=[{"role": "user", "content": text}]).input_tokens
    except Exception:
        seg = text[:500_000]
        n = _API.messages.count_tokens(model=_MODEL,
            messages=[{"role": "user", "content": seg}]).input_tokens
        return round(n * len(text) / len(seg))

def ntok_file(path):
    return ntok(open(path).read())

# Locate the big log (generated by ch4/make_log.py); fall back across common spots.
APPLOG = next((p for p in ("app.log", "../ch4/app.log", "../../ch4/app.log",
                           "sample-repo/app.log") if os.path.isfile(p)), None)
if not APPLOG:
    sys.exit("ERROR: app.log not found. Generate it first, e.g. "
             "`python3 ../ch4/make_log.py && cp ../ch4/app.log .` then rerun.")

# Real token sizes of what each tool returned into context.
claude_tok   = ntok_file("sample-repo/CLAUDE.md")
applog_tok   = ntok_file(APPLOG)
payments_tok = ntok_file("sample-repo/src/payments.py")
cache_tok    = ntok_file("sample-repo/src/cache.py")
grep_out     = subprocess.run(["grep","-n","ERROR",APPLOG], capture_output=True, text=True).stdout
grep_tok     = ntok(grep_out)
edit_diff    = ("--- a/src/payments.py\n+++ b/src/payments.py\n@@ reconcile @@\n"
                "-    delta = delta - 1  # stray off-by-one\n+    # fixed: no spurious decrement\n")
edit_tok     = ntok(edit_diff)

rows = []
def user(t): rows.append({"type": "user", "text": t})
def asst(inp, out, tools): rows.append({"type": "assistant",
    "usage": {"input_tokens": inp, "output_tokens": out}, "tool_calls": tools})

# Billed input/output per turn — real counts of representative prompt/reply text.
SYS = "You are a senior coding assistant. Money is integer cents. Cite file:line."
def billed_in(*msgs):  return ntok(SYS + "\n" + "\n".join(msgs))
def billed_out(reply): return ntok(reply)

u1 = "find the failing payment and explain it"
user(u1)
asst(billed_in(u1), billed_out("I'll start by reading the project memory and the log."),
     [{"name": "Read", "input": {"file": "CLAUDE.md"}, "result_tokens": claude_tok}])
asst(billed_in(u1), billed_out("Reading the application log to locate the error."),
     [{"name": "Read", "input": {"file": "app.log"}, "result_tokens": applog_tok}])  # the hotspot
asst(billed_in(u1), billed_out("Grepping for ERROR to pinpoint the failing charge."),
     [{"name": "Grep", "input": {"pattern": "ERROR"}, "result_tokens": grep_tok}])

u2 = "now check src and propose a fix"
user(u2)
asst(billed_in(u1, u2), billed_out("Inspecting the payment handler and cache module."),
     [{"name": "Read", "input": {"file": "src/payments.py"}, "result_tokens": payments_tok},
      {"name": "Read", "input": {"file": "src/cache.py"}, "result_tokens": cache_tok}])
asst(billed_in(u1, u2), billed_out("Applying the one-line fix to reconcile()."),
     [{"name": "Edit", "input": {"file": "src/payments.py"}, "result_tokens": edit_tok}])

with open("sample_session.jsonl", "w") as f:
    for r in rows:
        f.write(json.dumps(r) + "\n")
print(f"wrote sample_session.jsonl ({len(rows)} records) — real token counts via count_tokens")
print(f"  (app.log read = {applog_tok:,} tokens, counted directly)")
